// Generates extension/lib/icons.js from lucide-static (ISC licence) so the extension ships icons locally.
const fs = require('fs'), path = require('path');
const names = ['layers-2', 'moon', 'copy-x', 'bookmark', 'history', 'settings-2', 'chart-column', 'save', 'folder-tree', 'search', 'x', 'download', 'upload', 'plus', 'chevron-up', 'chevron-down', 'shield-check', 'sparkles', 'undo-2', 'trash-2', 'layout-dashboard', 'app-window', 'clock', 'lock', 'eye-off', 'archive-restore', 'pencil', 'external-link', 'check', 'zap', 'keyboard', 'circle-help', 'globe', 'key-round', 'arrow-right', 'sun', 'monitor', 'rotate-ccw', 'briefcase-business', 'mail', 'code-xml', 'bot', 'users', 'play', 'shopping-bag', 'wallet', 'newspaper', 'folder', 'circle-dashed', 'pin'];
const out = {};
for (const n of names) {
  const svg = fs.readFileSync(path.join(__dirname, 'node_modules/lucide-static/icons', n + '.svg'), 'utf8');
  out[n] = svg.replace(/<!--.*?-->/s, '').match(/<svg[^>]*>([\s\S]*?)<\/svg>/)[1].replace(/\s+/g, ' ').trim();
}
const js = `// Icons from Lucide (https://lucide.dev), ISC licence. Generated by test/make-icon-set.js.
const P = ${JSON.stringify(out, null, 0)};
export function icon(name, size = 18, cls = '') {
  return \`<svg class="ic \${cls}" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${P[name] || ''}</svg>\`;
}
// Replace <i data-icon="name" data-size="16"></i> placeholders in static HTML.
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach(el => { el.outerHTML = icon(el.dataset.icon, +(el.dataset.size || 18), el.className || ''); });
}
`;
fs.writeFileSync(path.join(__dirname, '../extension/lib/icons.js'), js);
console.log('icons:', Object.keys(out).length);
